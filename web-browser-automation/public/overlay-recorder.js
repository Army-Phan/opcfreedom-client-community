  function extractElementFeatures(el) {
    if (!el || el === document.body) return null;
    const tag = el.tagName.toLowerCase();
    const text = (el.innerText || el.value || el.textContent || '').trim().substring(0, 100);
    const attributes = {};
    const anchorAttrs = ['href', 'data-ved', 'data-testid', 'data-id', 'jsname', 'jscontroller', 'role', 'name', 'placeholder', 'type', 'aria-label', 'title'];
    for (const attr of anchorAttrs) {
      const val = el.getAttribute(attr);
      if (val !== null && val !== '') {
        attributes[attr] = val.substring(0, 150);
      }
    }
    const parent = el.parentElement;
    const rect = el.getBoundingClientRect();
    return {
      tag: tag,
      text: text,
      attributes: attributes,
      parentTag: parent ? parent.tagName.toLowerCase() : '',
      parentClass: parent && parent.className && typeof parent.className === 'string' ? parent.className.split(/\s+/).slice(0, 2).join(' ') : '',
      boundingBox: {
        x: Math.round(rect.left + window.scrollX),
        y: Math.round(rect.top + window.scrollY),
        viewportX: Math.round(rect.left),
        viewportY: Math.round(rect.top),
        width: Math.round(rect.width),
        height: Math.round(rect.height)
      }
    };
  }

  function getOptimalSelector(el, relativeTo = null) {
    if (!el || el === document.body || el === document.documentElement) return 'body';

    // 0. Priority Anchor Data/JS Attributes (Invariant anchors like data-ved, data-testid, jsname, jscontroller, role)
    const anchorAttrs = ['data-testid', 'data-id', 'jsname', 'jscontroller', 'data-ved'];
    for (const attr of anchorAttrs) {
      const val = el.getAttribute(attr);
      if (val && !val.includes(' ') && !val.includes('"') && !val.includes("'")) {
        const attrSel = `${el.tagName.toLowerCase()}[${attr}='${val}']`;
        try {
          const matches = (relativeTo || document).querySelectorAll(attrSel);
          if (matches.length === 1 && matches[0] === el) return attrSel;
        } catch (e) {}
      }
    }

    // Also check if ancestor has invariant anchor attribute and we are a structural child (e.g., div[data-ved] h3 or div[jscontroller] a)
    let parentNode = el.parentElement;
    let depth = 0;
    while (parentNode && parentNode !== document.body && depth < 3) {
      for (const attr of anchorAttrs) {
        const val = parentNode.getAttribute(attr);
        if (val && !val.includes(' ') && !val.includes('"') && !val.includes("'")) {
          const ancestorSel = `${parentNode.tagName.toLowerCase()}[${attr}='${val}'] ${el.tagName.toLowerCase()}`;
          try {
            const matches = (relativeTo || document).querySelectorAll(ancestorSel);
            if (matches.length === 1 && matches[0] === el) return ancestorSel;
          } catch (e) {}
        }
      }
      parentNode = parentNode.parentElement;
      depth++;
    }

    // 1. Check valid ID (not autogenerated numeric strings)
    if (el.id && !/^\d+$/.test(el.id) && !el.id.includes(':') && !el.id.includes('.')) {
      const idSel = `#${el.id}`;
      try {
        const matches = (relativeTo || document).querySelectorAll(idSel);
        if (matches.length === 1 && matches[0] === el) return idSel;
      } catch (e) {}
    }

    // 2. For form inputs/buttons, try name or attribute selectors with single quotes
    if (el.getAttribute('name')) {
      const nameSel = `${el.tagName.toLowerCase()}[name='${el.getAttribute('name')}']`;
      try {
        const matches = (relativeTo || document).querySelectorAll(nameSel);
        if (matches.length === 1 && matches[0] === el) return nameSel;
      } catch (e) {}
    }

    if (el.getAttribute('aria-label')) {
      const ariaSel = `[aria-label='${el.getAttribute('aria-label').replace(/'/g, "\\'")}']`;
      try {
        const matches = (relativeTo || document).querySelectorAll(ariaSel);
        if (matches.length === 1 && matches[0] === el) return ariaSel;
      } catch (e) {}
    }

    if (el.getAttribute('role') === 'button' || el.tagName.toLowerCase() === 'button') {
      const text = el.innerText ? el.innerText.trim() : '';
      if (text && text.length < 30 && !text.includes('\n')) {
        // Playwright has-text or text selector helper when inside Playwright, but pure CSS selector is safer
      }
    }

    // 3. Try unique combinations of classes
    if (el.className && typeof el.className === 'string') {
      const classes = el.className
        .split(/\s+/)
        .filter(c => c && !c.includes(':') && !c.includes('/') && !c.startsWith('hover:') && !c.startsWith('active:') && !c.includes('active') && !c.includes('focus'));
      
      if (classes.length > 0) {
        // Try all classes together
        const classSel = `${el.tagName.toLowerCase()}.${classes.slice(0, 3).join('.')}`;
        try {
          const matches = (relativeTo || document).querySelectorAll(classSel);
          if (matches.length === 1 && matches[0] === el) return classSel;
        } catch (e) {}
      }
    }

    // 4. Build structural path up to root or parent
    let path = [];
    let curr = el;
    while (curr && curr !== document.body && curr !== relativeTo) {
      let nodeSel = curr.tagName.toLowerCase();
      if (curr.id && !/^\d+$/.test(curr.id) && !curr.id.includes(':')) {
        nodeSel += `#${curr.id}`;
        path.unshift(nodeSel);
        break;
      } else if (curr.className && typeof curr.className === 'string') {
        const validClass = curr.className.split(/\s+/).find(c => c && !c.includes(':') && !c.includes('/') && !c.includes('active') && !c.includes('hover'));
        if (validClass) {
          nodeSel += `.${validClass}`;
        }
      }

      // Check sibling index if needed
      if (curr.parentElement) {
        const siblings = Array.from(curr.parentElement.children).filter(child => child.tagName === curr.tagName);
        if (siblings.length > 1) {
          const index = siblings.indexOf(curr) + 1;
          nodeSel += `:nth-of-type(${index})`;
        }
      }

      path.unshift(nodeSel);
      curr = curr.parentElement;
    }

    const fullSel = path.join(' > ');
    try {
      const matches = (relativeTo || document).querySelectorAll(fullSel);
      if (matches.length === 1 && matches[0] === el) return fullSel;
    } catch (e) {}

    return fullSel;
  }

  // Smart heuristic to detect whether the user is extracting from a repeating list or a single item
  function analyzeExtraction(targetEl) {
    const selectionText = window.getSelection().toString().trim();
    const el = targetEl || lastHoveredElement || document.activeElement || document.body;

    // Check if element is part of a repeating container (table rows, list items, card grid)
    let container = el;
    let repeatingContainer = null;
    let itemSelector = null;

    while (container && container !== document.body) {
      if (container.parentElement) {
        const siblings = Array.from(container.parentElement.children).filter(child => 
          child !== container && child.tagName === container.tagName && child.className === container.className
        );
        if (siblings.length >= 2) {
          repeatingContainer = container.parentElement;
          let baseSel = container.tagName.toLowerCase();
          if (container.className && typeof container.className === 'string') {
            const cls = container.className.split(/\s+/).filter(c => c && !c.includes(':'))[0];
            if (cls) baseSel += `.${cls}`;
          }
          itemSelector = baseSel;
          break;
        }
      }
      container = container.parentElement;
    }

    if (repeatingContainer && itemSelector) {
      // It's a multiple items scrape
      const fields = {};
      
      // Look inside the item for common extraction targets (title, link, image, price/score)
      const firstItem = repeatingContainer.querySelector(itemSelector) || el;
      const heading = firstItem.querySelector('h1, h2, h3, h4, .title, [class*="title"], strong');
      const link = firstItem.querySelector('a[href]');
      const img = firstItem.querySelector('img[src]');
      
      if (heading && getOptimalSelector(heading, firstItem)) {
        fields['title'] = getOptimalSelector(heading, firstItem);
      } else if (firstItem.innerText) {
        fields['content'] = 'self';
      }

      if (link && getOptimalSelector(link, firstItem)) {
        fields['url'] = `${getOptimalSelector(link, firstItem)}@href`;
      }

      if (img && getOptimalSelector(img, firstItem)) {
        fields['image'] = `${getOptimalSelector(img, firstItem)}@src`;
      }

      // Fallback if no specific subfields found
      if (Object.keys(fields).length === 0) {
        fields['text'] = 'self';
      }

      return {
        scope: 'multiple',
        selector: getOptimalSelector(firstItem),
        fields: fields,
        sampleText: selectionText || (firstItem.innerText ? firstItem.innerText.trim().substring(0, 100) : '')
      };
    } else {
      // Single element scrape
      const fields = {};
      const sel = getOptimalSelector(el);
      
      if (el.tagName === 'A' && el.getAttribute('href')) {
        fields['text'] = sel;
        fields['url'] = `${sel}@href`;
      } else if (el.tagName === 'IMG' && el.getAttribute('src')) {
        fields['image_url'] = `${sel}@src`;
      } else {
        fields['extracted_text'] = sel;
      }

      return {
        scope: 'single',
        selector: sel,
        fields: fields,
        sampleText: selectionText || (el.innerText ? el.innerText.trim().substring(0, 100) : '')
      };
    }
  }

